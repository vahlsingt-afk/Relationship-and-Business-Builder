def _check_card_projection_in_sync(card_id: str = "jeff-wayman"):
    """Read-only assertion: GET /cards/{id} reports canonical == frontmatter.

    Closes TOUCHCONTACT-VALIDATION-CONFLICT-001 — exposes when the materialized
    RC card frontmatter has drifted from the canonical baseline last_touch.
    """
    r = client.get(f"/cards/{card_id}", headers=headers)
    if r.status_code != 200:
        return False, f"GET /cards/{card_id} -> {r.status_code}"
    data = r.json()
    if data.get("projection_status") != "in_sync":
        return (
            False,
            f"projection_status={data.get('projection_status')!r}; "
            f"canonical={data.get('canonical', {}).get('last_touch')!r} "
            f"frontmatter={data.get('frontmatter', {}).get('last_touch')!r}",
        )
    return True, (
        f"in_sync at last_touch={data['canonical']['last_touch']}"
    )


def _check_touch_projection_round_trip(card_id: str = "jeff-wayman"):
    """Round-trip mutation: touch advances baseline + card frontmatter, then
    reverts. Validates the response shape introduced for
    TOUCHCONTACT-PROJECTION-SYNC-001 and leaves canonical state unchanged.
    """
    from datetime import date, timedelta
    # Capture initial state
    r = client.get(f"/cards/{card_id}", headers=headers)
    if r.status_code != 200:
        return False, f"pre-state GET /cards/{card_id} -> {r.status_code}"
    initial = r.json()
    if initial.get("projection_status") != "in_sync":
        return False, f"pre-condition not in_sync: {initial.get('projection_status')}"
    original = initial["canonical"]["last_touch"]
    # Pick a sentinel distinct from `original` so the round-trip exercises a
    # real rewrite. Default: today; fall back to today-1 if today == original.
    new_date = date.today().isoformat()
    if new_date == original:
        new_date = (date.today() - timedelta(days=1)).isoformat()
    # Advance
    r = client.post(
        "/touch", headers=headers, json={"id": card_id, "date": new_date},
    )
    if r.status_code != 200:
        return False, f"advance POST /touch -> {r.status_code}: {r.text[:160]}"
    advance = r.json()
    expected = {
        "ok": True, "id": card_id, "last_touch": new_date,
        "baseline_updated": True, "card_exists": True, "card_updated": True,
    }
    for k, v in expected.items():
        if advance.get(k) != v:
            return False, f"advance response field {k!r}={advance.get(k)!r} (expected {v!r})"
    if advance.get("card_reason") not in ("replaced", "added"):
        return False, f"advance card_reason={advance.get('card_reason')!r}"
    # Verify projection sync after advance
    after = client.get(f"/cards/{card_id}", headers=headers).json()
    if after.get("projection_status") != "in_sync":
        return False, f"post-advance projection_status={after.get('projection_status')!r}"
    if (
        after["canonical"]["last_touch"] != new_date
        or after["frontmatter"]["last_touch"] != new_date
    ):
        return False, (
            f"post-advance values diverged: canonical={after['canonical']['last_touch']!r} "
            f"frontmatter={after['frontmatter']['last_touch']!r}"
        )
    # Revert
    r = client.post(
        "/touch", headers=headers, json={"id": card_id, "date": original},
    )
    if r.status_code != 200:
        return False, f"revert POST /touch -> {r.status_code}: {r.text[:160]}"
    final = client.get(f"/cards/{card_id}", headers=headers).json()
    if (
        final.get("projection_status") != "in_sync"
        or final["canonical"]["last_touch"] != original
        or final["frontmatter"]["last_touch"] != original
    ):
        return False, (
            f"post-revert state inconsistent: status={final.get('projection_status')!r} "
            f"canonical={final['canonical']['last_touch']!r} "
            f"frontmatter={final['frontmatter']['last_touch']!r}"
        )
    return True, f"round-trip OK ({original} -> {new_date} -> {original})"


def _check_linkedin_zip_auto_ingest():
    """Regression for RB 9.0 LinkedIn ZIP auto-routing.

    A known LinkedIn export artifact must classify as linkedin_export_zip and
    the dry-run ingest response must contain deltas, recommendations, and
    visualization data. This is the trust-generating layer that prevents the
    generic "what do you want me to do with this file?" failure.
    """
    fixture = Path(tempfile.gettempdir()) / "rb_api_smoke_linkedin_export.zip"
    with zipfile.ZipFile(fixture, "w") as z:
        z.writestr(
            "Connections.csv",
            "Notes\nMore notes\n"
            "First Name,Last Name,URL,Email Address,Company,Position,Connected On\n"
            "Todd,Lennig,https://www.linkedin.com/in/atoddlennig,,"
            "Southern Tier Bookkeeping and Tax Services,Professional Bookkeeper,29 Apr 2025\n"
            "Smoke,Leader,https://www.linkedin.com/in/smokeleader,,"
            "Restaurant AI Co,Chief Revenue Officer,20 May 2026\n",
        )
        z.writestr("messages.csv", "FROM,TO,DATE,SUBJECT,CONTENT\na,b,2026-05-20,,hello\n")
    r = client.post("/artifacts/classify", headers=headers, json={"path": str(fixture)})
    if r.status_code != 200:
        return False, f"classify -> {r.status_code}: {r.text[:160]}"
    classified = r.json()
    if classified.get("artifact_type") != "linkedin_export_zip":
        return False, f"artifact_type={classified.get('artifact_type')!r}"
    r = client.post(
        "/linkedin/ingest",
        headers=headers,
        json={"path": str(fixture), "ingest_date": "2026-05-21", "dry_run": True},
    )
    if r.status_code != 200:
        return False, f"ingest dry-run -> {r.status_code}: {r.text[:160]}"
    body = r.json()
    required = {
        "summary_markdown": bool(body.get("summary_markdown")),
        "recommended_actions": bool(body.get("recommended_actions")),
        "network_visualization": bool(body.get("network_visualization")),
        "delta_intelligence": bool(body.get("delta_intelligence")),
        "baseline_comparison": "## Baseline Comparison" in (body.get("summary_markdown") or ""),
        "graph_mutations": "## Graph Mutations" in (body.get("summary_markdown") or ""),
        "persistence_verification": "## Persistence Verification" in (body.get("summary_markdown") or ""),
        "new_connections": body.get("headline_counts", {}).get("new_connections") == 1,
    }
    missing = [k for k, ok in required.items() if not ok]
    if missing:
        return False, f"missing/failed fields: {missing}"
    return True, "LinkedIn ZIP classified and dry-run RI enhancement returned deltas/actions/visualization"


# Extra validations that go beyond status-code checks. Each entry is
#   (label, callable -> (ok: bool, message: str))
# These run after the GET/POST status checks.
def _check_smart_loops_apply_no_write_without_confirm():
    """The apply endpoint must not write loops unless confirm=true.

    This is the smoke-level enforcement of the smoke-test-mutations rule and
    P-009 confirmed-execution discipline. We compare the loop-ledger row
    count before and after a confirm=false call; any delta means the gate
    leaked.
    """
    import rb_core
    before = sum(1 for L in rb_core.parse_loop_ledger())
    r = client.post(
        "/smart_loops/apply",
        headers=headers,
        json={"confirm": False},
    )
    if r.status_code != 200:
        return False, f"POST /smart_loops/apply (confirm=false) -> {r.status_code}: {r.text[:160]}"
    body = r.json()
    if body.get("confirmed") is not False:
        return False, f"confirmed={body.get('confirmed')!r} (expected false)"
    if body.get("applied_count", 0) != 0:
        return False, f"applied_count={body.get('applied_count')} (expected 0)"
    after = sum(1 for L in rb_core.parse_loop_ledger())
    if after != before:
        return False, f"loop ledger grew from {before} to {after} rows with confirm=false"
    fresh = body.get("fresh") or []
    if fresh and not all(p.get("apply_status") == "not_confirmed" for p in fresh):
        return False, "at least one fresh proposal missing apply_status='not_confirmed'"
    return True, f"confirm=false preview returned {len(fresh)} fresh proposal(s); ledger unchanged ({before} rows)"



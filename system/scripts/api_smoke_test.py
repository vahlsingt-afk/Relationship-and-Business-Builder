def run() -> int:
    failures = 0
    total = len(GET_CHECKS) + len(POST_CHECKS) + len(EXTRA_VALIDATIONS)
    print(f"{'endpoint':<60} {'status':<8}")
    print("-" * 75)
    for url, _ in GET_CHECKS:
        try:
            r = client.get(url, headers=headers)
            ok = r.status_code == 200
            print(f"GET {url:<56} {r.status_code:<8}")
            if not ok:
                failures += 1
                print(f"    body: {r.text[:200]}")
        except Exception as e:
            failures += 1
            print(f"GET {url:<56} EXCEPT {type(e).__name__}: {str(e)[:50]}")
    for url, body in POST_CHECKS:
        try:
            r = client.post(url, headers=headers, json=body)
            ok = r.status_code == 200
            print(f"POST {url:<55} {r.status_code:<8}")
            if not ok:
                failures += 1
                print(f"    body: {r.text[:200]}")
            elif url == "/test_traces":
                # Clean up the smoke trace files we just wrote so the
                # test doesn't accumulate debris in system/test_traces/.
                try:
                    data = r.json()
                    for key in ("md_file", "json_file"):
                        rel = data.get(key)
                        if rel:
                            (SYSTEM_DIR.parent / rel).unlink(missing_ok=True)
                except Exception:
                    pass
        except Exception as e:
            failures += 1
            print(f"POST {url:<55} EXCEPT {type(e).__name__}: {str(e)[:50]}")
    for label, fn in EXTRA_VALIDATIONS:
        try:
            ok, msg = fn()
            tag = "OK" if ok else "FAIL"
            print(f"CHK {label:<56} {tag:<8}")
            if not ok:
                failures += 1
                print(f"    {msg}")
            else:
                print(f"    {msg}")
        except Exception as e:
            failures += 1
            print(f"CHK {label:<56} EXCEPT {type(e).__name__}: {str(e)[:80]}")
    print("-" * 75)
    if failures == 0:
        print(f"All {total} endpoints pass.")
        return 0
    print(f"{failures}/{total} failed.")
    return 1


if __name__ == "__main__":
    sys.exit(run())
